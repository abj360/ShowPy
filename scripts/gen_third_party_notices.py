#!/usr/bin/env python3

"""
gen_third_party_notices.py --- writes the licence notices of the Rust crates linked into e8s._core

cargo-about reports the licences of e8s-py's dependency graph, the crate built as e8s._core, with
build and dev dependencies left out and our own unpublished crates ignored (about.toml), and
takes each licence text from the crates' own sources. Proc macros are normal dependencies but run
only at compile time, so the notice keeps only the crates that `cargo tree` lists on normal edges
without proc macros, for every target: the crates linked into the extension, each once. Both
tools run offline on the locked graph, so the same Cargo.lock always gives the same bytes. The
cargo-about it runs is the one `nox -s rust` installs into .cargo-tools at the pinned version.

Contains:
    NOTICE_FILE: the notice file the wheel ships, relative to the repository root
    LicenceBlock: one licence text and the linked crates it covers
    cargo_about(): returns the path of the cargo-about that the rust session installs
    parse_cargo_tree(): reads the package names and versions of a `cargo tree` listing
    linked_licences(): keeps the licences of linked crates from a cargo-about report, each crate
        once
    format_notices(): renders licence blocks as the notice text
    render_notices(): runs cargo about and cargo tree and returns the notice text
    notice_licences(): lists the licence ids a notice text names, sorted and without repeats
    notice_crates(): lists the crates a notice text names, in order
    gen_third_party_notices(): writes the notice file, or with check compares it; returns the
        exit code
    main(): parses --check and returns gen_third_party_notices' exit code
"""

import argparse
import json
import re
import subprocess
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTICE_FILE = Path("e8s/licenses/THIRD_PARTY_RUST.txt")
CARGO_TOOLS_BIN = Path(".cargo-tools/bin")
EXTENSION_PACKAGE = "e8s-py"
EXTENSION_MANIFEST = "crates/e8s-py/Cargo.toml"
ABOUT_CONFIG = "about.toml"
LINKED_EDGES = "normal,no-proc-macro"
INSTALL_COMMAND = "uv run nox -s rust"
GENERATE_COMMAND = "uv run python scripts/gen_third_party_notices.py"
RULE = "=" * 80
NOTICE_HEADER = (
    "Third-party Rust crates linked into e8s._core\n"
    "\n"
    "Generated by scripts/gen_third_party_notices.py. Where a crate offers a choice of\n"
    "licences, the licence named below is the one e8s takes it under.\n"
)
# Each licence block opens with an 80-character rule; a licence text never does.
LICENCE_HEADER = re.compile(rf"^{RULE}\nLicense: (?P<licence>[^\n]+)$", re.MULTILINE)
USED_BY = re.compile(
    rf"^{RULE}\nLicense: [^\n]+\nUsed by:\n(?P<crates>(?: {{4}}[^\n]+\n)+)", re.MULTILINE
)
# `cargo tree --format {p}` prints `name vX.Y.Z`, then a path or a `(*)` repeat marker.
TREE_PACKAGE = re.compile(r"^(?P<name>\S+) v(?P<version>\S+)")
ERROR_EXIT = 2


@dataclass(frozen=True)
class LicenceBlock:
    """Holds one licence text and the linked crates that the notice names under it.

    Attributes:
        licence: The SPDX id of the licence.
        crates: Each crate as `name version`, once, in cargo-about's order.
        text: The licence text as the crates ship it.
    """

    licence: str
    crates: tuple[str, ...]
    text: str


def cargo_about(root: Path = ROOT) -> Path:
    """Returns the path of the cargo-about that `nox -s rust` installs under a checkout."""
    name = "cargo-about.exe" if sys.platform == "win32" else "cargo-about"
    return root / CARGO_TOOLS_BIN / name


def parse_cargo_tree(listing: str) -> frozenset[tuple[str, str]]:
    """Reads the package names and versions of a `cargo tree --prefix none` listing.

    Args:
        listing: The output of `cargo tree --prefix none --format {p}`.

    Returns:
        packages: Each package as `(name, version)`, once.
    """
    matches = (TREE_PACKAGE.match(line) for line in listing.splitlines())
    return frozenset((match["name"], match["version"]) for match in matches if match)


def _mapping(value: object) -> Mapping[str, object]:
    """Returns a JSON object of the cargo-about report, or rejects any other value."""
    if not isinstance(value, Mapping):
        raise TypeError(f"cargo-about report: expected an object, found {value!r:.60}")
    return value


def _items(value: object) -> list[object]:
    """Returns a JSON array of the cargo-about report, or rejects any other value."""
    if not isinstance(value, list):
        raise TypeError(f"cargo-about report: expected an array, found {value!r:.60}")
    return value


def _text(value: object) -> str:
    """Returns a JSON string of the cargo-about report, or rejects any other value."""
    if not isinstance(value, str):
        raise TypeError(f"cargo-about report: expected a string, found {value!r:.60}")
    return value


def linked_licences(
    report: Mapping[str, object], linked: frozenset[tuple[str, str]]
) -> list[LicenceBlock]:
    """Keeps the licences of linked crates from a cargo-about report, each crate once.

    Args:
        report: cargo-about's JSON report, parsed.
        linked: The `(name, version)` of every crate linked into the extension.

    Returns:
        blocks: Per licence text in the report's order, its linked crates; a licence no linked
            crate carries is left out.
    """
    blocks = []
    for licence in _items(report.get("licenses")):
        entry = _mapping(licence)
        crates: dict[str, None] = {}
        for user in _items(entry.get("used_by")):
            crate = _mapping(_mapping(user).get("crate"))
            name, version = _text(crate.get("name")), _text(crate.get("version"))
            if (name, version) in linked:
                crates[f"{name} {version}"] = None
        if crates:
            blocks.append(
                LicenceBlock(_text(entry.get("id")), tuple(crates), _text(entry.get("text")))
            )
    return blocks


def format_notices(blocks: Sequence[LicenceBlock]) -> str:
    """Renders licence blocks as the notice text, ending in exactly one newline."""
    sections = [NOTICE_HEADER]
    for block in blocks:
        crates = "".join(f"    {crate}\n" for crate in block.crates)
        body = block.text.rstrip("\n")
        sections.append(f"{RULE}\nLicense: {block.licence}\nUsed by:\n{crates}\n{body}\n")
    return "\n".join(sections)


def _run(root: Path, *command: str) -> str:
    """Runs one command in the checkout and returns its standard output."""
    done = subprocess.run(command, cwd=root, check=True, capture_output=True)
    return done.stdout.decode("utf-8")


def render_notices(root: Path = ROOT) -> str:
    """Runs cargo about over e8s-py's linked crates and returns the notice text.

    Args:
        root: The repository checkout whose locked graph is read.

    Returns:
        notices: The rendered notice text, ending in exactly one newline.

    Raises:
        FileNotFoundError: cargo-about is not installed under root; the message gives the fix.
        subprocess.CalledProcessError: cargo could not fetch the locked crates, or cargo or
            cargo-about failed, for example on a crate whose licence it cannot identify.
        TypeError: cargo-about's report does not have the expected shape.
    """
    tool = cargo_about(root)
    if not tool.is_file():
        raise FileNotFoundError(f"cargo-about not found at {tool}; run: {INSTALL_COMMAND}")
    _run(root, "cargo", "fetch", "--locked")
    listing = _run(
        root,
        *("cargo", "tree", "--frozen", "-p", EXTENSION_PACKAGE, "--target", "all"),
        *("-e", LINKED_EDGES, "--prefix", "none", "--format", "{p}"),
    )
    report = _run(
        root,
        *(str(tool), "generate", "--frozen", "--fail", "--format", "json"),
        *("--manifest-path", EXTENSION_MANIFEST, "--config", ABOUT_CONFIG),
    )
    return format_notices(linked_licences(_mapping(json.loads(report)), parse_cargo_tree(listing)))


def notice_licences(text: str) -> list[str]:
    """Lists the licence ids that a notice text names in its licence headers.

    Args:
        text: A notice text from format_notices.

    Returns:
        licences: Each id once, sorted.
    """
    return sorted({match["licence"] for match in LICENCE_HEADER.finditer(text)})


def notice_crates(text: str) -> list[str]:
    """Lists the crates that a notice text names under its licence headers.

    Args:
        text: A notice text from format_notices.

    Returns:
        crates: Each `name version` line, in order, repeats kept.
    """
    return [
        line.strip() for match in USED_BY.finditer(text) for line in match["crates"].splitlines()
    ]


def gen_third_party_notices(*, check: bool, root: Path = ROOT) -> int:
    """Writes the notice file, or with check compares it with a fresh rendering.

    Args:
        check: Compare instead of writing, and fail when the committed file is stale.
        root: The repository checkout to render and write in.

    Returns:
        exit_code: 0 when written or current, 1 when stale, 2 when rendering failed.
    """
    try:
        notices = render_notices(root).encode("utf-8")
    except (FileNotFoundError, TypeError) as error:
        print(f"E: {error}", file=sys.stderr)
        return ERROR_EXIT
    except subprocess.CalledProcessError as error:
        detail = error.stderr.decode("utf-8", errors="replace").strip().splitlines()
        print(f"E: {' '.join(error.cmd)} failed: {detail[-1] if detail else ''}", file=sys.stderr)
        return ERROR_EXIT
    notice = root / NOTICE_FILE
    if not check:
        notice.parent.mkdir(parents=True, exist_ok=True)
        notice.write_bytes(notices)
        print(f"Wrote {NOTICE_FILE.as_posix()}")
        return 0
    if not notice.is_file() or notice.read_bytes() != notices:
        print(f"E: {NOTICE_FILE.as_posix()} is stale; run: {GENERATE_COMMAND}", file=sys.stderr)
        return 1
    print(f"Checked {NOTICE_FILE.as_posix()}")
    return 0


def main(argv: list[str] | None = None) -> int:
    """Parses --check and returns gen_third_party_notices' exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1] if __doc__ else None)
    parser.add_argument(
        "--check", action="store_true", help="fail when the committed notice file is stale"
    )
    return gen_third_party_notices(check=parser.parse_args(argv).check)


if __name__ == "__main__":
    sys.exit(main())
