#!/usr/bin/env python3

"""
gen_error_codes.py --- generates the error-code docs and the core's Rust error enums

Writes docs/error-codes.md and crates/e8s-core/src/base/error_codes.rs from the ErrorCode
catalogue and the E8sError classes. Run without arguments to rewrite both files; run with
--check to exit 1 when either has drifted.

Contains:
    code_meanings(): reads each ErrorCode member's docstring from its source
    error_kinds(): reads each class of the E8sError family with its docstring's first line
    code_variant(): names the Rust ErrorCode variant of a code
    kind_variant(): names the Rust ErrorKind variant of an error class
    rust_raisers(): finds the classes the core raises each code with, from its Rust sources
    code_raisers(): finds the classes that raise or report each code in the library and the core
    render_docs(): renders the Markdown table of code, raising classes and meaning
    render_rust(): renders the Rust ErrorCode and ErrorKind enums
    main(): rewrites both generated files, or checks them with --check
"""

import argparse
import ast
import re
import sys
import textwrap
from collections import defaultdict
from collections.abc import Mapping
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIBRARY_ROOT = ROOT / "e8s"
CATALOGUE_PATH = LIBRARY_ROOT / "core" / "error_codes.py"
ERRORS_PATH = LIBRARY_ROOT / "core" / "errors.py"
DOCS_PATH = ROOT / "docs" / "error-codes.md"
CRATES_ROOT = ROOT / "crates"
RUST_PATH = CRATES_ROOT / "e8s-core" / "src" / "base" / "error_codes.rs"
ENUM_NAME = "ErrorCode"
BASE_ERROR = "E8sError"
KIND_SUFFIX = "Error"
# A core raise site names its class and its code together: `ErrorKind::Schema, ErrorCode::Schema`.
RUST_RAISE = re.compile(r"ErrorKind::(?P<kind>\w+),\s*ErrorCode::(?P<code>\w+)")
RUST_SOURCE_FOLDER = "src"
RUST_LINE_WIDTH = 100
FIX_COMMAND = "uv run python scripts/gen_error_codes.py"
HEADER = """# Error codes

Audience: code that handles e8Show errors and validation reports. Scope: every code a
`E8sError` raises or a `ValidationIssue` reports.

Generated by `uv run python scripts/gen_error_codes.py` from the `ErrorCode` docstrings in
`e8s/core/error_codes.py` and the raise sites in `e8s/` and `crates/`; do not edit by hand.

"""
COLUMNS = ("Code", "Raised by", "Meaning")
RUST_HEADER = """\
// Generated by `uv run python scripts/gen_error_codes.py`; do not edit by hand.
//! error_codes --- the error codes and exception classes of the core, mirrored from e8s.core
//!
//! Contains:
//!     ErrorCode: names every error and issue code the library raises or reports
//!     ErrorCode::as_str(): returns the code's text, the value of its Python member
//!     ErrorKind: names each class of the E8sError family
//!     ErrorKind::class_name(): returns the name of the class in e8s.core.errors
"""


def code_meanings() -> dict[str, str]:
    """Reads each ErrorCode member's docstring, the string literal that follows it.

    Returns:
        meanings: Member name to its one-line docstring, in source order.
    """
    tree = ast.parse(CATALOGUE_PATH.read_text(encoding="utf-8"))
    enum = next(
        node for node in tree.body if isinstance(node, ast.ClassDef) and node.name == ENUM_NAME
    )
    meanings: dict[str, str] = {}
    for index, statement in enumerate(enum.body):
        if not (isinstance(statement, ast.Assign) and isinstance(statement.targets[0], ast.Name)):
            continue
        name = statement.targets[0].id
        doc = _string_value(enum.body[index + 1]) if index + 1 < len(enum.body) else ""
        if not doc:
            raise SystemExit(f"E: {ENUM_NAME}.{name} has no docstring")
        meanings[name] = doc
    return meanings


def error_kinds() -> dict[str, str]:
    """Reads each class of the E8sError family, E8sError first, in source order.

    Returns:
        kinds: Class name to the first line of its docstring.
    """
    tree = ast.parse(ERRORS_PATH.read_text(encoding="utf-8"))
    kinds: dict[str, str] = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        bases = {base.id for base in node.bases if isinstance(base, ast.Name)}
        if node.name == BASE_ERROR or bases & kinds.keys():
            kinds[node.name] = (ast.get_docstring(node) or "").splitlines()[0]
    return kinds


def code_variant(code: str) -> str:
    """Names the Rust ErrorCode variant of a code: `BAD_ID` becomes `BadId`."""
    return "".join(part.capitalize() for part in code.split("_"))


def kind_variant(class_name: str) -> str:
    """Names the Rust ErrorKind variant of an error class: `SchemaError` becomes `Schema`."""
    return class_name.removesuffix(KIND_SUFFIX)


def _string_value(statement: ast.stmt) -> str:
    """Returns the stripped text of a bare string statement, or "" for any other statement."""
    if (
        isinstance(statement, ast.Expr)
        and isinstance(statement.value, ast.Constant)
        and isinstance(statement.value.value, str)
    ):
        return statement.value.value.strip()
    return ""


def _annotation_name(node: ast.expr | None) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def _call_name(call: ast.Call) -> str | None:
    if isinstance(call.func, ast.Name):
        return call.func.id
    if isinstance(call.func, ast.Attribute):
        return call.func.attr
    return None


def _raiser(chain: list[ast.AST], returns: dict[str, str | None]) -> str | None:
    """Names the class that carries a code, from the code's ancestors, innermost first.

    A comparison is a check, not a raise, so it names nothing. A call names its class, or the
    return type of a local helper; a class body names that class (its `default_code`); an
    enclosing function names its return type.
    """
    for node in chain:
        if isinstance(node, ast.Compare):
            return None
        if isinstance(node, ast.Call):
            name = _call_name(node)
            if name is not None and name[:1].isupper():
                return name
            if name in returns:
                return returns[name]
        if isinstance(node, ast.ClassDef):
            return node.name
        if isinstance(node, ast.FunctionDef):
            return _annotation_name(node.returns)
    return None


def _returns(tree: ast.Module) -> dict[str, str | None]:
    return {
        node.name: _annotation_name(node.returns)
        for node in ast.walk(tree)
        if isinstance(node, ast.FunctionDef)
    }


def _module_raisers(
    tree: ast.Module, shared: Mapping[str, str] | None = None
) -> list[tuple[str, str]]:
    """Lists (code, class) for each ErrorCode member a module raises or reports.

    Args:
        tree: The module's syntax tree.
        shared: Classes returned by functions of other library modules, so a call to an imported
            issue builder names its class; the module's own functions take precedence.

    Returns:
        found: One (member name, class name) pair per use of a member that names a class.
    """
    parents = {child: node for node in ast.walk(tree) for child in ast.iter_child_nodes(node)}
    returns = {**(shared or {}), **_returns(tree)}
    found: list[tuple[str, str]] = []
    for node in ast.walk(tree):
        if not (
            isinstance(node, ast.Attribute)
            and isinstance(node.value, ast.Name)
            and node.value.id == ENUM_NAME
        ):
            continue
        chain: list[ast.AST] = []
        current: ast.AST = node
        while current in parents:
            current = parents[current]
            chain.append(current)
        raiser = _raiser(chain, returns)
        if raiser is not None:
            found.append((node.attr, raiser))
    return found


def rust_raisers() -> dict[str, list[str]]:
    """Finds the classes the core raises each code with, from the crates' Rust sources.

    Only `src/` folders count; the generated enums are skipped.

    Returns:
        raisers: Member name to the sorted names of the classes the core raises it with.
    """
    codes = {code_variant(code): code for code in code_meanings()}
    kinds = {kind_variant(name): name for name in error_kinds()}
    raisers: dict[str, set[str]] = defaultdict(set)
    for path in sorted(CRATES_ROOT.rglob("*.rs")):
        if path == RUST_PATH or RUST_SOURCE_FOLDER not in path.relative_to(CRATES_ROOT).parts:
            continue
        for found in RUST_RAISE.finditer(path.read_text(encoding="utf-8")):
            if found["code"] in codes and found["kind"] in kinds:
                raisers[codes[found["code"]]].add(kinds[found["kind"]])
    return {code: sorted(names) for code, names in raisers.items()}


def code_raisers() -> dict[str, list[str]]:
    """Finds the classes that raise or report each code in the library and the core.

    Returns:
        raisers: Member name to the sorted names of the classes that carry it.
    """
    raisers: dict[str, set[str]] = defaultdict(set)
    paths = [path for path in sorted(LIBRARY_ROOT.rglob("*.py")) if path != CATALOGUE_PATH]
    trees = [ast.parse(path.read_text(encoding="utf-8")) for path in paths]
    shared = {
        name: returned
        for tree in trees
        for node in tree.body
        if isinstance(node, ast.FunctionDef)
        for name, returned in [(node.name, _annotation_name(node.returns))]
        if returned is not None
    }
    for tree in trees:
        for code, raiser in _module_raisers(tree, shared):
            raisers[code].add(raiser)
    for code, names in rust_raisers().items():
        raisers[code].update(names)
    return {code: sorted(names) for code, names in raisers.items()}


def _table(rows: list[tuple[str, str, str]]) -> str:
    """Renders rows as a Markdown table padded the way Prettier pads one."""
    widths = [max(len(row[i]) for row in [COLUMNS, *rows]) for i in range(len(COLUMNS))]

    def line(cells: tuple[str, ...]) -> str:
        return "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths, strict=True)) + " |"

    rule = "| " + " | ".join("-" * w for w in widths) + " |"
    return "\n".join([line(COLUMNS), rule, *(line(row) for row in rows)]) + "\n"


def render_docs() -> str:
    """Renders docs/error-codes.md: one table row per code, sorted by code.

    Returns:
        markdown: The file's full text.
    """
    raisers = code_raisers()
    rows = [
        (
            f"`{code}`",
            ", ".join(f"`{name}`" for name in raisers.get(code, [])),
            meaning.replace("|", "\\|"),
        )
        for code, meaning in sorted(code_meanings().items())
    ]
    return HEADER + _table(rows)


def _rust_doc(text: str, indent: str) -> list[str]:
    """Wraps one docstring line into `///` lines that fit the line width."""
    prefix = f"{indent}/// "
    return [f"{prefix}{line}" for line in textwrap.wrap(text, RUST_LINE_WIDTH - len(prefix))]


def _rust_enum(name: str, doc: str, variants: dict[str, str]) -> list[str]:
    """Renders one fieldless Rust enum with a doc line per variant."""
    lines = [
        f"/// {doc}",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        f"pub enum {name} {{",
    ]
    for variant, variant_doc in variants.items():
        lines += [*_rust_doc(variant_doc, "    "), f"    {variant},"]
    return [*lines, "}"]


def _rust_names(name: str, method: str, doc: str, names: dict[str, str]) -> list[str]:
    """Renders an impl block whose one method maps each variant to its Python name."""
    return [
        f"impl {name} {{",
        f"    /// {doc}",
        "    #[must_use]",
        f"    pub const fn {method}(self) -> &'static str {{",
        "        match self {",
        *(f'            Self::{variant} => "{text}",' for variant, text in names.items()),
        "        }",
        "    }",
        "}",
    ]


def render_rust() -> str:
    """Renders crates/e8s-core/src/base/error_codes.rs: the ErrorCode and ErrorKind enums.

    Returns:
        source: The file's full text, formatted as rustfmt formats it.
    """
    meanings = dict(sorted(code_meanings().items()))
    kinds = error_kinds()
    for variants in ([code_variant(code) for code in meanings], [kind_variant(k) for k in kinds]):
        if len(set(variants)) != len(variants):
            raise SystemExit("E: two codes or two classes share one Rust variant name")
    blocks = [
        _rust_enum(
            "ErrorCode",
            "Names every error and issue code the library raises or reports.",
            {code_variant(code): meaning for code, meaning in meanings.items()},
        ),
        _rust_names(
            "ErrorCode",
            "as_str",
            "Returns the code's text, the value of its member of the Python `ErrorCode`.",
            {code_variant(code): code for code in meanings},
        ),
        _rust_enum(
            "ErrorKind",
            "Names each class of the E8sError family, so the binding raises the class it names.",
            {kind_variant(name): doc for name, doc in kinds.items()},
        ),
        _rust_names(
            "ErrorKind",
            "class_name",
            "Returns the name of the class in `e8s.core.errors`.",
            {kind_variant(name): name for name in kinds},
        ),
    ]
    return RUST_HEADER + "".join("\n" + "\n".join(block) + "\n" for block in blocks)


def _check(path: Path, rendered: str) -> bool:
    """Tells whether a generated file holds exactly what its renderer gives, reporting drift."""
    if path.read_text(encoding="utf-8") == rendered:
        return True
    print(f"E: {path.relative_to(ROOT)} is stale; run: {FIX_COMMAND}")
    return False


def main(argv: list[str] | None = None) -> int:
    """Rewrites docs/error-codes.md and the Rust enums, or with --check reports drift.

    Args:
        argv: Command-line arguments; defaults to sys.argv.

    Returns:
        status: 0 when both files are current or were rewritten, 1 when --check finds drift.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if a file has drifted")
    args = parser.parse_args(argv)
    outputs = {DOCS_PATH: render_docs(), RUST_PATH: render_rust()}
    if args.check:
        fresh = [_check(path, rendered) for path, rendered in outputs.items()]
        return 0 if all(fresh) else 1
    for path, rendered in outputs.items():
        path.write_text(rendered, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
