#!/usr/bin/env python3

"""
gen_public_api.py --- generates e8s/__init__.py from the PUBLIC_API table

Run without arguments to rewrite the file; run with --check to exit 1 when it has drifted.

Contains:
    render_init(): renders the formatted source of e8s/__init__.py from PUBLIC_API
    main(): rewrites e8s/__init__.py, or checks it with --check
"""

import argparse
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INIT_PATH = ROOT / "e8s" / "__init__.py"
FIX_COMMAND = "uv run python scripts/gen_public_api.py"

HEADER = '''"""
__init__.py --- the public API of e8s, the choreography library

Every public function and class of the library is importable from here, lazily: a name
is imported on first use (PEP 562). Internal helper modules (engine compilation, matching
cost and solver internals, workspace documents) are not re-exported. One name clashes and
is renamed: the motion function spiral is `spiral_motion`; `spiral` is the geometric spiral
curve. Subpackages: core, geo, time, cast, sheet, choreo, show.

Generated by scripts/gen_public_api.py from e8s/_api_table.py; do not edit by hand.

Contains:
    __version__: reports the installed e8s distribution version
    __all__: lists every re-exported name
    __getattr__(): imports and caches a public name on first use
    __dir__(): lists the public API
"""

import importlib
from importlib.metadata import version
from typing import TYPE_CHECKING

__version__: str = version("e8s")

'''

FOOTER = '''

def __getattr__(name: str) -> object:
    """Imports a public name on first use, so `import e8s.<module>` stays light.

    The resolved object is stored in the module namespace, so later lookups skip this function.
    """
    if name not in _EXPORTS:
        raise AttributeError(f"module 'e8s' has no attribute {name!r}")
    module_name, attribute = _EXPORTS[name]
    value: object = getattr(importlib.import_module(module_name), attribute)
    globals()[name] = value
    return value


def __dir__() -> list[str]:
    """Lists the public API."""
    return sorted(__all__)
'''


def _public_api() -> tuple[tuple[str, str, str], ...]:
    """Loads PUBLIC_API lazily so importing this script has no side effects."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from e8s._api_table import PUBLIC_API

    return PUBLIC_API


def _is_constant(name: str) -> bool:
    return name.isupper()


def _import_order(name: str) -> tuple[int, str]:
    """Returns the isort order-by-type key: constants, then classes, then everything else."""
    if _is_constant(name):
        return (0, name.lower())
    if name[0].isupper():
        return (1, name.lower())
    return (2, name.lower())


def _render_type_checking_block() -> str:
    """Renders the `if TYPE_CHECKING:` block, one import statement per module."""
    plain: dict[str, list[str]] = defaultdict(list)
    aliased: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for name, module, attribute in _public_api():
        if name == attribute:
            plain[module].append(name)
        else:
            aliased[module].append((attribute, name))
    lines = ["if TYPE_CHECKING:"]
    for module in sorted(plain.keys() | aliased.keys()):
        if plain[module]:
            lines.append(f"    from {module} import (")
            lines += [f"        {name}," for name in sorted(plain[module], key=_import_order)]
            lines.append("    )")
        lines += [
            f"    from {module} import {attribute} as {name}"
            for attribute, name in sorted(aliased[module])
        ]
    return "\n".join(lines) + "\n"


def _render_tables() -> str:
    """Renders the `_EXPORTS` mapping and the `__all__` list."""
    exports = [
        f'    "{name}": ("{module}", "{attribute}"),' for name, module, attribute in _public_api()
    ]
    ordered = sorted(
        (name for name, _, _ in _public_api()), key=lambda name: not _is_constant(name)
    )
    names = [f'    "{name}",' for name in ordered]
    return "\n".join(
        [
            "_EXPORTS: dict[str, tuple[str, str]] = {",
            *exports,
            "}",
            "",
            "__all__ = [",
            *names,
            "]",
        ]
    )


def _format(source: str) -> str:
    """Formats source with ruff so the output matches `ruff format --check`."""
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(INIT_PATH), "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    return result.stdout


def render_init() -> str:
    """Renders the formatted source of e8s/__init__.py from PUBLIC_API."""
    body = "\n".join([_render_type_checking_block(), _render_tables()])
    return _format(HEADER + body + FOOTER)


def main(argv: list[str] | None = None) -> int:
    """Rewrites e8s/__init__.py, or with --check reports drift.

    Args:
        argv: Command-line arguments; defaults to sys.argv.

    Returns:
        exit_code: 0 when the file is current or was rewritten, 1 when --check finds drift.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if __init__.py is stale")
    args = parser.parse_args(argv)
    rendered = render_init()
    if args.check:
        if INIT_PATH.read_text() == rendered:
            return 0
        print(f"E: e8s/__init__.py is stale; run: {FIX_COMMAND}", file=sys.stderr)
        return 1
    INIT_PATH.write_text(rendered)
    print("Wrote e8s/__init__.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
