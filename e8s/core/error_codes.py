"""
error_codes.py --- the catalogue of every code an E8sError raises or a ValidationIssue reports

Each member's value equals its name, so stored and logged codes read the same as before the
catalogue existed. The string under each member says when the code is raised or reported.

Contains:
    ErrorCode: names every error and issue code the library raises or reports
"""

from enum import StrEnum, unique


@unique
class ErrorCode(StrEnum):
    """Names every error and issue code the library raises or reports.

    >>> ErrorCode.LOCKED == "LOCKED"
    True
    """

    ALREADY_MEMBER = "ALREADY_MEMBER"
    """A text form edit adds a spot that is already one of the form's members."""
    AMBIGUOUS_PATH = "AMBIGUOUS_PATH"
    """A workspace path names a set folder that matches the folder of a different set."""
    AUDIO_DUPLICATE = "AUDIO_DUPLICATE"
    """Two audio tracks of a timeline share one label."""
    AUDIO_RANGE = "AUDIO_RANGE"
    """An audio track's section is not a (start, end) range inside the show."""
    BAD_FONT = "BAD_FONT"
    """A font file is not a valid font or breaks a font cap."""
    BAD_ID = "BAD_ID"
    """A repository id is not 64-digit hex, or a show, set, note or form ID cannot be stored."""
    BAD_PATH = "BAD_PATH"
    """A show id or workspace path cannot be stored, or names a directory where a file belongs."""
    BAD_SHAPE = "BAD_SHAPE"
    """A similarity fit gets point arrays that are not matched (N, 2) arrays of numbers."""
    BAD_TRANSITION = "BAD_TRANSITION"
    """A transition pin names a transition ID that does not parse as `a→b`."""
    COINCIDENT_SLOTS = "COINCIDENT_SLOTS"
    """Every spread of a text stroke's spots would put two of them within 1 µm."""
    CONFLICT = "CONFLICT"
    """A write was based on a revision that another write has since replaced."""
    CONTINUITY = "CONTINUITY"
    """A path does not end on its target placement."""
    CORE_PANIC = "CORE_PANIC"
    """A compiled core function panicked; the panic is a bug in e8s, caught at the boundary."""
    CORRUPT = "CORRUPT"
    """A stored repository is damaged or is missing a blob it refers to."""
    COUNTS_MISMATCH = "COUNTS_MISMATCH"
    """A transition's paths span a different number of counts than its target set."""
    CUE_DUPLICATE = "CUE_DUPLICATE"
    """Two cues of a timeline share one label."""
    CUE_NEGATIVE = "CUE_NEGATIVE"
    """A cue's estimated duration is negative."""
    DEGENERATE = "DEGENERATE"
    """The landmarks of a similarity fit sit on top of each other."""
    FAR_OFF_SHEET = "FAR_OFF_SHEET"
    """A placement lies more than FAR_OFF_SHEET_M meters past the sheet's bounding box."""
    FONT_HASH_MISMATCH = "FONT_HASH_MISMATCH"
    """Font bytes do not hash to the URI or pinned hash that names them."""
    FONT_NAME_TAKEN = "FONT_NAME_TAKEN"
    """A font registers under a name that is already bound to different font bytes."""
    GEOMETRY = "GEOMETRY"
    """A shape is degenerate, such as a zero radius or collinear arc points."""
    HOLD_NEGATIVE = "HOLD_NEGATIVE"
    """A hold sits before count 0 or lasts a negative number of counts."""
    HOLD_OVERLAP = "HOLD_OVERLAP"
    """Two holds of a timeline share one count."""
    INACTIVE_ON_FIELD = "INACTIVE_ON_FIELD"
    """A spot marked inactive stands on the field in a set."""
    IO = "IO"
    """The file system fails while a file repository reads or writes."""
    KEY_MISMATCH = "KEY_MISMATCH"
    """A mapping key differs from the ID of the item it holds."""
    LOCKED = "LOCKED"
    """An edit touches a pinned or locked item without `force=True`."""
    MARKER_DUPLICATE = "MARKER_DUPLICATE"
    """Two markers of a timeline share one label."""
    MARKER_RANGE = "MARKER_RANGE"
    """A marker falls outside the show's counts."""
    MATCH = "MATCH"
    """An assignment of spots to slots has no feasible solution."""
    MEASURE_LENGTH = "MEASURE_LENGTH"
    """A measure length is not positive or a measure change count is negative."""
    MEMBER_COUNT_MISMATCH = "MEMBER_COUNT_MISMATCH"
    """A text form has a different number of members than slots."""
    MEMBER_MISMATCH = "MEMBER_MISMATCH"
    """A form lists a spot as a member, but that spot's placement does not name the form."""
    MISSING_EXTRA = "MISSING_EXTRA"
    """A function needs an optional dependency whose e8s extra is not installed."""
    MISSING_FONT = "MISSING_FONT"
    """A font name or URI is not held by the font registry."""
    MISSING_GLYPH = "MISSING_GLYPH"
    """No font in the chain has a glyph for a character of the text."""
    MISSING_SPOT = "MISSING_SPOT"
    """A spot of the cast has no placement in a set."""
    MIXED_OPERATORS = "MIXED_OPERATORS"
    """A selector mixes `&` with `+` or `-` at one parenthesis level without parentheses."""
    NAME_TAKEN = "NAME_TAKEN"
    """A named selection or a proposal is created under a name that is already taken."""
    NAME_TOO_LONG = "NAME_TOO_LONG"
    """A file repository path is longer than the file system allows."""
    NOT_A_MEMBER = "NOT_A_MEMBER"
    """A text form edit removes a spot that is not one of the form's members."""
    NOT_A_TEXT_FORM = "NOT_A_TEXT_FORM"
    """A text-only operation gets a form of another kind."""
    NOT_FINITE = "NOT_FINITE"
    """A similarity fit or a stored show field holds a NaN or infinite number."""
    NOT_SERIALIZABLE = "NOT_SERIALIZABLE"
    """A model that is never stored, such as a registry of functions, goes to or from JSON."""
    NOT_IN_FORM = "NOT_IN_FORM"
    """A placement names a form it is not a member of in that set."""
    NO_HARDLINKS = "NO_HARDLINKS"
    """The file system under a file repository cannot create hard links."""
    N_OR_SPACING = "N_OR_SPACING"
    """A text form request gives both or neither of `n` and `spacing`."""
    OLD_FORMAT = "OLD_FORMAT"
    """A write would store a show.json of an older format version than this release writes."""
    PAST_THE_SHOW = "PAST_THE_SHOW"
    """A facing override starts on or after the last count of the show, so covers no show time."""
    PATH = "PATH"
    """A path instruction is invalid."""
    PINNED_CHANGED = "PINNED_CHANGED"
    """An edit changes a pinned placement."""
    PIN_MISMATCH = "PIN_MISMATCH"
    """A pin record covers a placement, form or path row that is not flagged locked."""
    PROPOSAL_CLOSED = "PROPOSAL_CLOSED"
    """A proposal that is already accepted, rejected or withdrawn is changed again."""
    PROPOSAL_STALE = "PROPOSAL_STALE"
    """An open proposal touches items that changed since its base revision, so it is not applied."""
    RAMP_CUT = "RAMP_CUT"
    """A tempo ramp is cut short by the next tempo section."""
    RAMP_INCOMPLETE = "RAMP_INCOMPLETE"
    """A tempo ramp sets only one of `ramp_to` and `ramp_counts`."""
    RAMP_LENGTH = "RAMP_LENGTH"
    """A tempo ramp lasts no counts."""
    RANGE_PADDING = "RANGE_PADDING"
    """A range's endpoints are spelled with different zero-padding, such as `T1-T010`."""
    READ_ONLY = "READ_ONLY"
    """A write targets a derived workspace file, which is read-only."""
    REFLECTION = "REFLECTION"
    """The landmarks of a similarity fit are mirrored between the two sheets."""
    RESERVED_MOTION = "RESERVED_MOTION"
    """A motion registry would bind a built-in motion name to another function."""
    SCHEMA = "SCHEMA"
    """Data fails its schema or text format."""
    SEGMENT_BOUND = "SEGMENT_BOUND"
    """A compiled path segment strays further from its motion than the engine allows."""
    SHOW_TOO_LONG = "SHOW_TOO_LONG"
    """The show's total counts exceed MAX_COUNTS."""
    SPACING = "SPACING"
    """Items do not fit in the space or count given."""
    STAGE = "STAGE"
    """A library failure that no more specific code describes."""
    STALE_FORM = "STALE_FORM"
    """A form's set no longer places that form."""
    STALE_TRANSITION = "STALE_TRANSITION"
    """A transition holds paths for, or a comment anchors to, two sets that are not consecutive."""
    STORAGE = "STORAGE"
    """A show cannot be persisted or read back."""
    STRICT_JSON = "STRICT_JSON"
    """Stored or imported JSON holds NaN, infinity, a repeated key, a BOM or a lone surrogate."""
    SURFACE = "SURFACE"
    """A point is off the sheet."""
    TEMPO_MISSING = "TEMPO_MISSING"
    """A timeline in counts mode has no tempo."""
    TEMPO_NONPOSITIVE = "TEMPO_NONPOSITIVE"
    """A tempo section's tempo is not positive."""
    TEMPO_ORDER = "TEMPO_ORDER"
    """Tempo sections are not in increasing count order, one per count."""
    TEMPO_START = "TEMPO_START"
    """The first tempo section does not start at count 0."""
    TEXT_COUNT_EDIT = "TEXT_COUNT_EDIT"
    """`edit` is asked to change a text form's spot count, which only `edit_text_count` does."""
    TIMELINE = "TIMELINE"
    """Tempo, measure or hold data is inconsistent."""
    TIME_RANGE = "TIME_RANGE"
    """A time is outside its range, or a start is not before its end."""
    TOO_FEW_POINTS = "TOO_FEW_POINTS"
    """A similarity fit gets fewer than two matched points."""
    TOO_FEW_SPOTS = "TOO_FEW_SPOTS"
    """A form or text asks for fewer spots than its curves or strokes need."""
    TOO_LARGE = "TOO_LARGE"
    """A repository file, or the history of a show, is over its size cap."""
    TOO_MANY_SETS = "TOO_MANY_SETS"
    """A show holds more sets than MAX_SETS."""
    TOO_MANY_SPOTS = "TOO_MANY_SPOTS"
    """A cast holds more spots than MAX_SPOTS, or a text form asks for more than its own cap."""
    TORN_SLOT = "TORN_SLOT"
    """A repository slot stays empty or cut short after every reread: its writer stopped early."""
    UNKNOWN_FORM = "UNKNOWN_FORM"
    """A placement names a form that does not exist."""
    UNKNOWN_FORMAT = "UNKNOWN_FORMAT"
    """A show.json or interchange document names no known format, or half a format header."""
    UNKNOWN_PIN = "UNKNOWN_PIN"
    """A pin names a spot, form, set or transition that is not in the show."""
    UNKNOWN_REF = "UNKNOWN_REF"
    """An ID, name or unit does not resolve."""
    UNKNOWN_SET = "UNKNOWN_SET"
    """A form or a comment anchor names a set that is not in the show."""
    UNKNOWN_SHEET = "UNKNOWN_SHEET"
    """The show's sheet reference does not resolve in the sheet store."""
    UNKNOWN_SPOT = "UNKNOWN_SPOT"
    """A set, transition, route, named selection or comment anchor names a spot not in the cast."""
    UNPINNED_SHEET = "UNPINNED_SHEET"
    """The show's dependencies do not pin its sheet reference."""
    VALIDATION = "VALIDATION"
    """A structural integrity check fails."""
    VERSION = "VERSION"
    """A pinned version is missing or incompatible, or a stored show is newer than this release."""
    ZERO_COUNTS = "ZERO_COUNTS"
    """A set after the first arrives in 0 counts."""
    ZERO_LENGTH = "ZERO_LENGTH"
    """The direction of a zero vector is requested."""
