def __getattr__(name: str) -> object:
    """Imports a public name on first use, so `import e8s.<module>` stays light.

    The resolved object is stored in the module namespace, so later lookups skip this function.
    """
    if name not in _EXPORTS:
        raise AttributeError(f"module 'e8s' has no attribute {name!r}")
    module_name, attribute = _EXPORTS[name]
    value: object = getattr(importlib.import_module(module_name), attribute)
    globals()[name] = value
    return value


def __dir__() -> list[str]:
    """Lists the public API."""
    return sorted(__all__)
